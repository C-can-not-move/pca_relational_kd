// src/kd/pcar_loss.h
//
// PCAR（PCA-Relational）损失：把师生的特征各自投影到 PCA 子空间，比【批内成对距离】。
//
// 为什么比距离而不是比特征：
//   教师是 resnet152、特征 2048；学生是 resnet18、特征 512。
//   维度不同 ⇒ 逐元素比没有意义。但"批内两两之间的距离"在两边都是 (B, B)，
//   天然对齐。这也是关系蒸馏相对 logit 蒸馏的好处：
//     · 教师的 fc 一次都不用调 ⇒ 不需要 wnid → 1000 类索引的映射
//     · 教师不需要见过这 200 个类
//
// 为什么要先做 PCA 再比距离：
//   PCA 是正交变换，只换坐标系、不丢信息（keep = 全部时）。
//   它的作用不是"压缩"，而是【选轴】：把方差最大的 keep 个方向留下，
//   让距离里主要反映"数据真正变化的方向"，而不是噪声维度上的抖动。
//   ⚠ 刻意不做白化：白化会把尺度信息抹平，而距离损失正需要尺度。
//
// 归一化的一个细节（最容易写错的地方）：
//   两个距离矩阵必须用【同一个标量】归一化 —— 用教师的平均距离。
//   若各自除以自己的均值，那么"形状像、整体尺度全错"会被当成完美匹配，
//   损失恒为 0，什么也学不到。
//
// 用法：
//     PcarLoss loss(/*student_dim=*/512, /*teacher_dim=*/2048, cfg);
//     // 第一趟，只累加统计量（不建图）
//     loss.add_student(fs);  loss.add_teacher(ft);
//     loss.finish_fit(device);              // 特征分解 + 把 μ/V 搬到 device
//     // 第二趟，每批
//     auto r = loss.forward(fs, ft);        // 学生侧带梯度，教师侧 detach
//     auto total = ce + cfg.lambda * r;
#pragma once

#include <cstdint>

#include <torch/torch.h>

#include "save/tensor_table.h"
#include "util/pca.h"

namespace prkd::kd
{
	// ==========================================================================
	// keep 取 128 时，这个方法到底在做什么
	// ==========================================================================
	//
	// 两组特征维数不同，但距离矩阵都是 (B, B)，所以比较成立：
	//     教师 resnet152 (B, 2048) → PCA 前 128 轴 → zt (B, 128)
	//     学生 resnet18  (B,  512) → PCA 前 128 轴 → zs (B, 128)
	//     两边 cdist → 两个 (B, B) → Huber 逐元素 → 一个标量
	//
	// keep=128 的实际含义（学生 512、教师 2048）：
	//     · 学生保留 128/512  = 25%
	//     · 教师保留 128/2048 = 6.25%
	//   这个数不是"压缩率"，是【选轴】：只保留方差最大的 128 个方向。
	//   丢掉的通常是幅度小、噪声大的抖动；把它们算进距离，会让"像不像"被噪声主导。
	//
	// 为什么可以放心丢：
	//   距离对【正交变换】不变：任意正交 U，||Uz_i − Uz_j|| = ||z_i − z_j||。
	//      keep = 全维  ⇒  PCA 对损失毫无影响（纯换坐标）
	//      keep < 全维  ⇒  唯一效应是"丢掉哪些方向"
	//   推论：本损失对坐标系免疫，只对【子空间的选择】敏感。
	//
	// 对照实验的写法（这才是研究要的）：
	//     两边都不投影（keep = 各自全维） → 退化成普通 RKD-D
	//     两边都取 128                    → 本方法默认
	//     两者 acc 之差 = "选轴"贡献了多少
	//   ⚠ 现在两边共用一个 keep；只把学生设成全维、教师仍截断，
	//     得到的是"只有教师降噪"，不是 RKD-D —— 要严格的对照组得拆成两个数。
	//
	// 刻意不做：白化（会抹平尺度，而距离损失正需要尺度）。
	// ==========================================================================
	//
	// ==========================================================================
	// 为什么训练中【不】重算 PCA 坐标系（尤其是学生侧）
	// ==========================================================================
	//
	// 学生的特征分布随权重变化，这一点没错：第一趟拟合出来的 128 个轴，
	// 到第 10 轮时已经不是它"当前方差最大的 128 个方向"了。但重算不是解法：
	//
	// ① 先看一个事实：全维时 PCA 对损失是空操作
	//      正交变换下距离不变 ⇒ 学生侧 keep=512 时，它做不做 PCA 完全一样。
	//      所以"学生的 PCA"只在 keep < 512 时存在 —— 它的全部作用是【选轴】。
	//
	// ② 每批重拟合会让相邻两步不可比
	//      批与批的样本不同 ⇒ 子空间不同 ⇒ rkd 在 step t 与 t+1 的数值不在同一把尺子上。
	//      损失曲线会出现锯齿，调参失去依据。
	//
	// ③ 更严重：坐标系跟着参数动会打开【退化解】
	//      若"用哪个坐标系看 D_s"由学生自己决定，它可以把差异大的方向挤到第 k 名之后，
	//      让被比较的子空间里"看起来很接近"—— 损失靠换坐标系下降，表征没变好。
	//      数学上这是规范自由度：约束与被约束的对象一起动，约束就不唯一。
	//
	// ④ 冻结之后它是什么
	//      (f − μ)·V 变成一个【固定的线性投影】，即一个秩 k 的半范数：
	//        · 可复现（同 seed、同 pca_samples ⇒ 同一组轴）
	//        · 无退化解（坐标系是常数，学生只能靠改特征来降损失）
	//      代价：轴"过时"——它只说明"不是最优的降噪方向"，不说明"损失错了"。
	//      这正是我们接受的取舍：宁要一个稳定但次优的投影，不要一个最优但可作弊的。
	//
	// ⑤ 存档存什么（2026-11-18 起）
	//      存的是【完整的 PCA】：mu (D,) 与 V (D, D)，外加特征值。
	//      不存"前 keep 列"——keep 是"怎么用它"，不是"它是什么"。
	//      于是 kd.keep 变成运行时参数：改 128 → 256 只需重读存档，不必重跑拟合。
	//      代价：教师侧 V 是 2048×2048 f32 = 16.8 MB，学生 512×512 = 1.0 MB。
	//      读档只认这个格式；旧版（前 keep 列、无特征值）直接抛，要求删档重拟合。
	//
	// ⑥ 真要让坐标系参与变化，唯一正当的写法是学一个映射
	//      z_s = (f_s − μ_t) · W ,  W: 512 → keep
	//      此时锚是教师的固定子空间，学生学的是"怎么把自己的特征映进去"。
	//      代价：W 会塌缩（把差异方向压到零），必须加正交/谱范数约束。
	// ==========================================================================

	// ==========================================================================
	// rkd 这个数怎么读（别拿 0.17 当 17% 看）
	// ==========================================================================
	//
	// 它是什么：
	//   两个【归一化后的】批内距离矩阵之间，逐元素 Huber 差的平均。
	//   0 = 批内结构完全一致；越大越不像。所以它是【不相似度】，不是相似度。
	//
	// 关键：Huber(δ=1) 在小残差处是平方，会把数值压小一半再平方
	//     |残差| < 1   huber = 0.5 × 残差²
	//     |残差| ≥ 1   huber = |残差| − 0.5
	//   所以"平均残差 a" 与 "rkd" 的关系是  rkd ≈ 0.5 · a²   （a < 1 时）
	//   反过来：  a ≈ √(2 · rkd)
	//
	// 换算表（以教师的平均距离为单位）：
	//     rkd 0.04  ≈  结构差 28%
	//     rkd 0.08  ≈  结构差 40%
	//     rkd 0.17  ≈  结构差 59%
	//     rkd 0.28  ≈  结构差 75%
	//     rkd 0      =  完全一致
	//   ⚠ 直接读 rkd 的数值会严重低估差异：0.17 不是 17%，是约 59%。
	//
	// 另外两层限定：
	//   ① 它衡量的是 keep 维子空间【内】的结构差；子空间外的差异不计入。
	//      所以换一组坐标系（比如续跑时重拟合）会改变这个值 —— 0.279 → 0.172
	//      那次不是模型变好，是"测的尺子"换了。
	//   ② 归一化用的是教师的平均距离；学生若整体尺度偏小，
	//      会额外贡献一个常数偏移（见 normalize 的说明）。
	//
	// 一句话：rkd 适合【同一次运行内】看趋势（它在慢慢掉 = 结构在靠拢），
	//         不适合【跨运行】比大小（坐标系不同，尺子就不同）。
	// ==========================================================================

	struct PcarConfig
	{
		int64_t keep   = 128;    // 保留的主轴数（师生取同样多，才能比距离）
		double  lambda = 25.0;   // 关系损失的权重（RKD 原文的量级）
		double  delta  = 1.0;    // Huber 的 δ：小于它按平方，大于它按线性
	};

	class PcarLoss
	{
	public:
		// dim 必须与各自网络的池化后特征维数一致：
		//   resnet18 → 512，resnet34 → 512，resnet152 → 2048
		PcarLoss(int64_t student_dim, int64_t teacher_dim, PcarConfig cfg);

		// ---------------- 第一趟：累加统计量 ----------------
		//
		// 只要 sum/平方和，不要结果 —— 分批各自做 PCA 再合并是错的
		// （子空间不能相加），能分批的只有统计量，见 util/pca.h。
		// 传入 (N, dim) 的 f32 特征；内部转 f64 并在 CPU 上累加。
		void add_student(const torch::Tensor& feat);
		void add_teacher(const torch::Tensor& feat);

		// 求 μ 与主方向，取前 keep 列并搬到 device 常驻。
		//   keep > 各自维数时按维数截断（并打印实际用的值）
		// 必须在 add_* 之后、forward 之前调用一次。
		void finish_fit(const torch::Device& device);

		// ---------------- 第二趟：每批的损失 ----------------
		//
		// student_feat (B, student_dim)  —— 允许带梯度
		// teacher_feat (B, teacher_dim)  —— 内部 detach，调用方不必包 NoGrad
		//
		// 返回标量：huber(D_s/scale, D_t/scale)，与 CE 相加由调用方负责。
		torch::Tensor forward(const torch::Tensor& student_feat,const torch::Tensor& teacher_feat);

		// ---------------- 坐标系的存取（"saved" 模式用）----------------
		//
		// 为什么要有这个：轴是在【某个时刻的学生特征】上拟合的。
		//   live  模式：每次启动都在当前学生上重拟合 ⇒ 断点前后换了尺子，
		//              rkd 会在断点处跳一次（0.279 → 0.172 那次就是）。
		//   saved 模式：第一次拟合后把 μ/V 存进 auto/pca.{txt,bin}，
		//              之后每次启动读回来 ⇒ 整条训练只用一把尺子。
		//
		// 存四个张量：mu_s / V_s / mu_t / V_t（f32，CPU，文本键表格式）。
		prkd::save::TensorMap dump_coords() const;
		// keep 由配置传入：存档里是完整 PCA，子空间维数由调用方决定
		void load_coords(const prkd::save::TensorMap& items,
			const torch::Device& device, int64_t keep);

		// ---------------- 诊断 ----------------
		int64_t keep()        const { return keep_; }
		double  last_scale()  const { return last_scale_; }   // 上一次 forward 用的归一化标量
		double  last_rkd()    const { return last_rkd_; }     // 上一次 loss 的数值（打印用）

		const PcarConfig& config() const { return cfg_; }

	private:
		PcarConfig cfg_;
		int64_t    keep_ = 0;

		prkd::util::Pca pca_s_;
		prkd::util::Pca pca_t_;

		// V 存【完整】矩阵 (D, D)：这样 kd.keep 变成运行时参数，
		// 换 keep 不必重拟合（存档里就是那份 PCA 本身，不是它的前 keep 列）。
		torch::Tensor mu_s_, V_s_;     // (Ds,) / (Ds, Ds)，常驻 device
		torch::Tensor mu_t_, V_t_;     // (Dt,) / (Dt, Dt)
		torch::Tensor Vs_use_, Vt_use_; // V 的前 keep_ 列（view，不占额外内存）
		// 为什么 V 存全而不是存前 keep 列：keep 是"用几列"，不是"有几列"。
		// 存全以后 kd.keep 可以随便改而不必重拟合；投影时切 view，零拷贝。

		// 全部特征值（降序，CPU f32）。只为两件事存在：
		//   ① finish_fit 里打印"前 keep 轴占多少方差"
		//   ② 从存档读回时【也能打印同一行】—— 否则读档的人看不到这个指标
		torch::Tensor eig_s_, eig_t_;
		bool          fitted_ = false;

		double last_scale_ = 0.0;
		double last_rkd_   = 0.0;
	};

}  // namespace prkd::kd
